import { browser, $, $$, expect } from '@wdio/globals';
import type { ModbusApi } from '../../src/shared/preload-api';

const view = () => $('.workbench-view:not([style*="display: none"])');
const snapshot = () => browser.execute(async () => (window as unknown as { modbus: ModbusApi }).modbus.getSnapshot());
const rail = (name: string) => $(`//nav//button[normalize-space(.)="${name}"]`).click();
async function fill(label: string, value: string) {
  const input = await view().$(`[aria-label="${label}"]`);
  await input.click(); await browser.keys(['Control', 'a']); await browser.keys('Backspace');
  if (value) await input.addValue(value);
  await expect(input).toHaveValue(value);
}

async function expectWidgetPosition() {
  const expected = (await snapshot()).workspace.canvases![0]!.widgets[0]!;
  const actual = await browser.execute(() => {
    const root = document.querySelector('.workbench-view:not([style*="display: none"])')!;
    const stage = root.querySelector('[data-testid="canvas-stage"]')!.getBoundingClientRect();
    const widget = root.querySelector('[data-widget-id]')!.getBoundingClientRect();
    return { x: widget.x - stage.x, y: widget.y - stage.y };
  });
  expect(Math.abs(actual.x - expected.x)).toBeLessThan(1);
  expect(Math.abs(actual.y - expected.y)).toBeLessThan(1);
}

