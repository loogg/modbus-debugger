const fs = require('fs');
const p = 'tests/unit/framer-streaming.test.ts';
let c = fs.readFileSync(p, 'utf8');
c = c.split(`    f.push(garbage, 0);
    f.push(garbage, 1);
    const out = f.tick(10);`).join(`    let out = f.push(garbage, 0);
    out = out.concat(f.push(garbage, 1));
    out = out.concat(f.tick(10));`);
fs.writeFileSync(p, c);
console.log('ok');